// Spieltest im Headless-Chromium mit Handy-Viewport. Screenshots in <outdir>.
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium, devices } = require('playwright');
const out = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices[process.argv[3] || 'iPhone 13'], hasTouch: true });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => { errs.push(e.message); console.log('PAGEERROR', e.message); });
await p.goto('file://' + process.cwd() + '/dist/index.html');
await p.waitForTimeout(1500);
const shot = async n => { await p.waitForTimeout(250); await p.screenshot({ path: `${out}/${n}.png` }); };
await shot('m1-title');
await p.tap('text=NEUES SPIEL'); await shot('m2-starter');
await p.tap('text=WÄHLEN >> nth=0'); await p.waitForTimeout(500); await shot('m3-hub');
await p.tap('text=SHOP'); await shot('m4-shop');
await p.tap('text=ZURÜCK'); await p.waitForTimeout(200);
await p.tap('text=TEAM'); await shot('m5-team');
await p.tap('text=ZURÜCK'); await p.waitForTimeout(200);
await p.tap('text=STARTEN'); await p.waitForTimeout(6000); await shot('m6-battle');
console.log('errors:', errs.length);
await b.close();
